#!/usr/bin/env python3
# ============================================================================
#  gen_config.py — generate a kernel .config without flex/bison
# ============================================================================
#  The Linux 5.10 Kconfig frontend needs flex and bison to build
#  scripts/kconfig/{lexer.lex.c,parser.tab.c}. In restricted build
#  environments those tools are often unavailable, and `make defconfig`
#  then fails before a single object file is compiled.
#
#  This script does the same job with kconfiglib (pure Python), producing:
#      .config
#      include/config/auto.conf
#      include/config/tristate.conf
#      include/generated/autoconf.h
#
#  It is only a bootstrap step: the real kconfig frontend is not needed
#  afterwards because `make` skips syncconfig when auto.conf is up to date.
# ============================================================================

import os
import sys
import argparse


def build_env(srctree, toolchain_bin):
    env = {
        # kconfiglib resolves $(srctree) from the environment; without this the
        # assembler probe in scripts/Kconfig.include fails with
        # "Sorry, this assembler is not supported."
        "srctree": srctree,
        "ARCH": "arm64",
        "SRCARCH": "arm64",
        "KERNELVERSION": "5.10.226",
        "CC": "clang",
        "LD": "ld.lld",
        "AR": "llvm-ar",
        "NM": "llvm-nm",
        "OBJCOPY": "llvm-objcopy",
        "OBJDUMP": "llvm-objdump",
        "READELF": "llvm-readelf",
        "STRIP": "llvm-strip",
        "CLANG_FLAGS": "-fintegrated-as",
        "PATH": toolchain_bin + ":" + os.environ.get("PATH", ""),
    }
    os.environ.update(env)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--srctree", required=True, help="kernel-5.10 source dir")
    ap.add_argument("--defconfig", required=True, help="path to defconfig file")
    ap.add_argument("--out", required=True, help="output dir (O=)")
    ap.add_argument("--toolchain-bin", required=True, help="clang bin dir")
    args = ap.parse_args()

    os.chdir(args.srctree)
    build_env(".", args.toolchain_bin)

    try:
        import kconfiglib
    except ImportError:
        sys.exit("kconfiglib is missing: pip install kconfiglib")

    kd = kconfiglib.Kconfig("Kconfig", warn_to_stderr=False)
    kd.load_config(args.defconfig, replace=True)

    out = args.out
    os.makedirs(os.path.join(out, "include", "config"), exist_ok=True)
    os.makedirs(os.path.join(out, "include", "generated"), exist_ok=True)

    kd.write_config(os.path.join(out, ".config"))
    kd.write_autoconf(os.path.join(out, "include", "config", "auto.conf"))

    # kconfiglib's header writer trips over bool symbols on some versions, so
    # emit autoconf.h ourselves.
    lines = [
        "/* Automatically generated by gen_config.py - do not edit */",
        "#ifndef AUTOCONF_INCLUDED",
        "#define AUTOCONF_INCLUDED",
    ]
    tristate = []
    for name, sym in kd.syms.items():
        if not sym.nodes:
            continue
        val = sym.tri_value
        if val == 2:
            tristate.append("CONFIG_%s=y" % name)
            if sym.type == kconfiglib.STRING:
                lines.append('#define CONFIG_%s "%s"' % (name, sym.str_value))
            elif sym.type in (kconfiglib.INT, kconfiglib.HEX):
                lines.append("#define CONFIG_%s %s" % (name, sym.str_value))
            else:
                lines.append("#define CONFIG_%s 1" % name)
        elif val == 1:
            tristate.append("CONFIG_%s=m" % name)
            lines.append("#define CONFIG_%s_MODULE 1" % name)
    lines.append("#endif")

    with open(os.path.join(out, "include", "generated", "autoconf.h"), "w") as f:
        f.write("\n".join(lines) + "\n")
    with open(os.path.join(out, "include", "config", "tristate.conf"), "w") as f:
        f.write("\n".join(tristate) + "\n")

    print("gen_config: %d symbols, %d y/m" % (len(kd.syms), len(tristate)))


if __name__ == "__main__":
    main()
